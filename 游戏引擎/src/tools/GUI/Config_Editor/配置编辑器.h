#pragma once
//============================================================================
// 配置编辑器 —— ImGui 界面层
// ---------------------------------------------------------------------------
// 布局：
//   ┌───────────────────────────────────────────────┐
//   │ 菜单栏：文件（重新加载/保存全部）· 帮助         │
//   ├───────────────┬───────────────────────────────┤
//   │ 实体列表       │ 属性编辑器                     │
//   │ (搜索过滤)     │  type / initialize_path       │
//   │  [+] 新建      │  decision_load_path           │
//   │  [×] 删除      │  acls / needed_events 列表    │
//   │  [×] 删除      │  校验结果区                   │
//   ├───────────────┴───────────────────────────────┤
//   │ 状态栏：当前文件 · 未保存标记 · 加载结果       │
//   └───────────────────────────────────────────────┘
//============================================================================

#include "src/tools/GUI/Config_Editor/实体配置模型.h"

//引擎命名空间
namespace engine
{
    //配置编辑器
    class 配置编辑器
    {
    public:
        //构造函数
        配置编辑器();

        //加载配置（从磁盘）
        void 加载();

        //每帧渲染
        void 渲染();

        // ———— 窗口关闭协调（主程序调用） ————

        //是否有未保存修改（用于关闭确认 / 状态栏提示）
        bool 未保存修改() const { return 有未保存修改; }
        //由 GLFW 关闭回调调用：记录一次关闭请求（有未保存修改时改为弹确认窗）
        void 请求关闭窗口() { 关闭请求 = true; }
        //用户已确认退出（主程序据此真正关闭窗口）
        bool 应关闭窗口() const { return 关闭已确认; }

    private:
        // ———— 数据 ————

        //实体配置仓库
        实体配置仓库 仓库;
        //脚本候选列表（initialize_path / decision_load_path 下拉共用）
        std::vector<std::string> 脚本列表;
        //选中实体索引（-1 表示未选中）
        int 选中索引 = -1;
        //搜索过滤文本
        std::string 搜索文本;
        //状态栏消息
        std::string 状态消息;
        //加载结果消息
        std::string 加载消息;
        //删除确认状态（防止误删）
        std::string 待确认删除类型;
        //新建实体类型输入缓冲
        std::string 新类型输入;
        //帮助窗口是否可见（菜单「帮助→使用说明」或 F1 打开）
        bool 显示帮助窗口 = false;

        // ———— 模块与格式（需求一/二） ————

        //当前浏览模块（Entity_Manager / Property_Manager / 自定义模块名）
        //决定左侧列表与右侧面板展示哪类配置
        std::string 当前模块 = "Entity_Manager";
        //新建配置时选择的目标模块（下拉框绑定）
        std::string 新建模块 = "Entity_Manager";
        //新建配置的条目名输入缓冲（实体格式=实体类型；属性槽格式=实体类型；自定义格式=条目名）
        std::string 新条目名输入;
        //当前选中的通用配置索引（-1 表示未选中；与 选中索引 互斥，分别对应各自模块）
        int 选中通用配置索引 = -1;
        //删除确认状态（通用配置）
        std::string 待确认删除条目;

        // ———— 配置格式管理窗口 ————

        //格式管理窗口是否可见（菜单「工具→配置格式管理」打开）
        bool 显示格式管理 = false;
        //当前正在编辑的格式（副本，保存时才写回仓库）
        配置格式 格式编辑;
        //正在编辑的格式是否有效（false 表示尚未选择任何格式）
        bool 格式编辑有效 = false;
        //新建模块名输入缓冲（格式管理窗口底部）
        std::string 新模块名输入;
        //新建字段名输入缓冲（格式管理窗口字段区）
        std::string 新字段名输入;
        //新建字段类型（格式管理窗口字段区下拉）
        配置字段类型 新字段类型 = 配置字段类型::文本;
        //新建字段必填标记
        bool 新字段必填 = true;
        //新建字段说明输入缓冲
        std::string 新字段说明输入;

        // ———— 未保存修改与关闭确认 ————

        //脏标记：任何编辑操作后置 true，保存成功后置 false
        bool 有未保存修改 = false;
        //关闭请求标志（主程序 GLFW 关闭回调置位）
        bool 关闭请求 = false;
        //用户已确认退出（主程序据此关闭窗口）
        bool 关闭已确认 = false;
        //关闭确认窗口是否可见（有未保存修改且收到关闭请求时弹出）
        bool 显示关闭确认 = false;

        // ———— 孤儿配置文件清理 ————

        //孤儿清理确认窗口是否可见（工具菜单触发）
        bool 显示孤儿清理 = false;
        //最近一次扫描发现的孤儿配置文件列表（确认后删除）
        std::vector<std::string> 孤儿清理列表;
        //孤儿清理扫描结果状态消息
        std::string 孤儿清理消息;

        // ———— 帮助窗口右侧的昔涟图片 ————

        //OpenGL 纹理 ID（0 = 未加载成功）
        unsigned int 帮助图片纹理 = 0;
        //图片像素尺寸
        int 帮助图片宽 = 0;
        int 帮助图片高 = 0;
        //是否已尝试加载（避免每次打开都做磁盘 IO）
        bool 帮助图片已尝试 = false;

        // ———— 界面子函数 ————

        //渲染菜单栏
        void 渲染菜单栏();
        //加载帮助窗口右侧的昔涟图片（stb_image 解码 + OpenGL 纹理），失败返回 false
        bool 加载帮助图片();
        //渲染帮助窗口（独立小窗：正文自动换行可滚动，右侧显示昔涟图片）
        void 渲染帮助窗口();
        //渲染右侧属性面板
        void 渲染属性面板();
        //渲染状态栏
        void 渲染状态栏();
        //渲染校验结果
        void 渲染校验结果(const 实体配置& cfg);
        //渲染校验结果通用块（错误/警告列表限高滚动；id 用于避免多个面板的 Child ID 冲突）
        void 渲染校验结果块(const char* id,
            const std::vector<std::string>& errors,
            const std::vector<std::string>& warnings,
            float 错误高度, float 警告高度);
        //渲染 acls 编辑列表
        void 渲染权限列表(实体配置& cfg);
        //渲染 needed_events 编辑列表
        void 渲染事件列表(实体配置& cfg);
        //渲染脚本选择器（文本输入 + 脚本下拉，label 用于避免多个选择器 ID 冲突，path 为要编辑的目标路径字段）
        void 渲染脚本选择器(const char* label, std::string& path);

        // ———— 模块与格式（需求一/二） ————

        //渲染左侧列表顶部的「新建配置」区（模块选择 + 条目名 + 创建按钮）
        void 渲染新建配置区();
        //渲染左侧列表（按 当前模块 显示对应配置）
        void 渲染模块列表();
        //渲染右侧面板（按 当前模块 分发）
        void 渲染模块面板();
        //渲染属性槽配置面板（Property_Manager 模块）
        void 渲染属性槽面板();
        //渲染通用配置面板（自定义模块）
        void 渲染通用配置面板();
        //渲染通用配置的单个字段编辑器（按格式字段定义动态生成控件）
        void 渲染通用字段编辑器(通用配置& cfg, const 配置格式& fmt);
        //渲染通用配置校验结果
        void 渲染通用校验结果(const 配置格式& fmt, const 通用配置& cfg);
        //渲染配置格式管理窗口（工具菜单打开：新建模块 + 自定义字段）
        void 渲染格式管理窗口();
        //把当前格式编辑副本写回仓库（保存到磁盘 + 更新内存）
        void 保存格式编辑();
        //构建模块候选列表（新建下拉与浏览下拉共用，消除重复代码）
        void 构建模块候选(std::vector<std::string>& 候选, std::vector<std::string>& 标签) const;
        //保存当前选中配置（Ctrl+S / 菜单共用；按 当前模块 分发，成功后清除脏标记）
        void 保存当前选中();
        //保存全部配置（实体 + 属性槽 + 通用配置；菜单「保存全部」与关闭确认共用）
        void 保存全部();
        //渲染关闭确认窗口（有未保存修改时弹出：保存并退出 / 直接退出 / 取消）
        void 渲染关闭确认窗口();
        //渲染孤儿配置文件清理窗口（列出扫描结果，确认后删除）
        void 渲染孤儿清理窗口();
    };
}
